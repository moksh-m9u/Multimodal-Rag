"""Answer endpoints: retrieve chunks, then generate an answer from them.

``/query`` returns the whole answer at once, ``/query/stream`` sends it token
by token over Server-Sent Events, and ``/query/custom`` lets the caller pick
the provider, model, and API key.
"""

from __future__ import annotations

import json

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import StreamingResponse

from api.custom_service import run_custom_query
from api.openapi_examples import (
    QUERY_PARAM_EXAMPLES,
    REQUEST_BODY_EXAMPLES,
    RICH_DESCRIPTION_COMMON,
    request_body_examples,
)
from api.schemas import CustomQueryRequest, CustomQueryResponse, QueryRequest, QueryResponse
from src.retrieval.generate import answer_query_stream

router = APIRouter(tags=["generation"])


@router.post(
    "/query",
    response_model=QueryResponse,
    summary="Retrieve chunks and generate an answer",
    description=(
        "Everything /retrieve returns, plus a complete answer generated by "
        "the multimodal LLM from the retrieved chunks.\n\n"
        "```json\n"
        "{\n"
        "  \"query\": \"Tell me about the pin configuration of the LM317.\",\n"
        "  \"top_k\": 10\n"
        "}\n"
        "```\n\n"
        "Answers are grounded in the retrieved chunks; no web search is used."
    )
    + RICH_DESCRIPTION_COMMON,
    response_description="Retrieved chunks plus the generated answer",
    openapi_extra=request_body_examples("QueryRequest", REQUEST_BODY_EXAMPLES),
)
async def query(request: Request, req: QueryRequest) -> QueryResponse:
    """Retrieve chunks and generate a full answer from the multimodal LLM."""
    try:
        answer, base, usage = await request.app.state.service.answer(req.query, req.top_k, req.max_images)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))
    return QueryResponse(
        **base.model_dump(),
        answer=answer,
        answer_characters=len(answer),
        usage=usage,
    )


def _sse(event: str, data: dict) -> str:
    """Format one Server-Sent Events frame."""
    return f"event: {event}\ndata: {json.dumps(data)}\n\n"


@router.get(
    "/query/stream",
    summary="Stream an answer over SSE",
    description=(
        "Streams the answer token-by-token over Server-Sent Events. Event flow:\n\n"
        "1. ``event: retrieval`` - full chunk payloads (like /retrieve),\n"
        "2. ``event: token``    - one per answer fragment (field ``delta``),\n"
        "3. ``event: done``     - final answer + ``response_id``,\n"
        "4. ``event: error``    - only on failure.\n\n"
        "Open the URL directly in a browser to watch the stream, or consume it "
        "with any SSE client. Works with e.g. ``curl -N``."
    ),
    response_description="text/event-stream of retrieval + answer tokens",
)
async def query_stream(
    request: Request,
    query: str = Query(
        ...,
        min_length=1,
        max_length=2000,
        description="The user's question about the documents.",
        examples=QUERY_PARAM_EXAMPLES,
    ),
    top_k: int = Query(
        10,
        ge=1,
        le=30,
        description="How many chunks to retrieve from the vector store.",
        examples=[10],
    ),
    max_images: int = Query(
        0,
        ge=0,
        le=50,
        description="Max images to send to the model (0 = all).",
        examples=[10],
    ),
) -> StreamingResponse:
    """Stream an answer over SSE.

    Emits a ``retrieval`` event (full chunk payloads), then one ``token`` event
    per answer chunk, then a final ``done`` event.  On failure an ``error``
    event is emitted instead.
    """
    service = request.app.state.service
    await service.ensure_ready()
    retriever = service.get_retriever(top_k)

    def generate():
        try:
            stream = answer_query_stream(retriever, query, max_images=max_images)
            chunks = stream.chunks
            base = service.to_retrieve_response(query, chunks)
            yield _sse("retrieval", base.model_dump())

            collected: list[str] = []
            for token in stream:
                collected.append(token)
                yield _sse("token", {"delta": token})

            answer = "".join(collected)
            yield _sse(
                "done",
                {
                    "answer": answer,
                    "answer_characters": len(answer),
                    "response_id": base.response_id,
                    "num_chunks": base.num_chunks,
                    "usage": stream.usage,
                },
            )
        except Exception as exc:
            yield _sse("error", {"message": str(exc)})

    return StreamingResponse(generate(), media_type="text/event-stream")


@router.post(
    "/query/custom",
    response_model=CustomQueryResponse,
    summary="Query with custom provider/model/API key",
    description=(
        "Retrieve chunks and generate an answer using a user-specified LLM "
        "provider, model, and API key.  Useful for comparing models or using "
        "personal API keys.\n\n"
        "The request body must include:\n"
        "- ``provider``: one of ``gemini``, ``groq``, ``huggingface``, ``openai``\n"
        "- ``model``: a valid model ID for that provider\n"
        "- ``api_key``: your personal API key for the provider\n"
        "- ``query``, ``top_k``, ``temperature``, ``max_tokens`` as usual"
    ),
    response_description="Retrieved chunks plus the generated answer with usage metadata",
    openapi_extra=request_body_examples("CustomQueryRequest", [
        {
            "summary": "Custom Gemini query",
            "value": {
                "query": "Tell me about the pin configuration of the LM2596.",
                "top_k": 10,
                "provider": "gemini",
                "model": "gemini-3.5-flash-lite",
                "api_key": "YOUR_GEMINI_API_KEY",
                "temperature": 0.0,
                "max_tokens": 512,
            },
        },
    ]),
)
async def query_custom(request: Request, req: CustomQueryRequest) -> CustomQueryResponse:
    """Retrieve chunks and generate an answer with a custom provider/model/key."""
    try:
        answer, base, usage = await run_custom_query(
            service=request.app.state.service,
            query=req.query,
            top_k=req.top_k,
            provider_id=req.provider,
            model_id=req.model,
            api_key=req.api_key,
            temperature=req.temperature,
            max_tokens=req.max_tokens,
            max_images=req.max_images,
            thinking=req.thinking,
        )
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))

    # Merge usage into base response
    from api.schemas import UsageMetadata
    usage_metadata = None
    if usage and "error" not in usage:
        usage_metadata = UsageMetadata(**usage)

    return CustomQueryResponse(
        **base,
        answer=answer,
        answer_characters=len(answer),
        usage=usage_metadata,
    )
